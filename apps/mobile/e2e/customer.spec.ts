import { readyImages } from './capture';
import { test, expect } from '@playwright/test';
test('variant cart, wishlist, guest merge, profile persistence, address and failure/retry', async ({ page }) => {
  await page.goto('/product/cotton-kurta', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Add to demo cart', exact: true }).click();
  await expect(page.getByText('Added to your demo cart.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Large · Cream', exact: true }).click();
  await page.getByRole('button', { name: 'Add to demo cart', exact: true }).click();
  await page.getByRole('button', { name: '♡ Save to wishlist', exact: true }).click();
  await expect(page.getByRole('button', { name: '♥ Saved to wishlist', exact: true })).toBeVisible();
  await page.goto('/account?returnTo=/cart', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Continue with local demo profile' }).click();
  await page.getByRole('textbox', { name: 'Demo profile name', exact: true }).fill('Sample');
  await page.getByRole('button', { name: 'Open demo profile', exact: true }).click();
  await expect(page.getByText('Medium · Cream', { exact: true })).toBeVisible();
  await expect(page.getByText('Large · Cream', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Large · Cream', { exact: true })).toBeVisible();
  await readyImages(page); await page.screenshot({ path: 'evidence/task-03-cart-390.png', fullPage: true });
  await page.goto('/wishlist', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('button', { name: 'View Everyday cotton kurta', exact: true })).toBeVisible();
  await page.goto('/account', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Add sample address', exact: true }).click();
  for (const [label, value] of [['Recipient name', 'Demo Recipient'], ['Mobile number', '9876543210'], ['Street address', 'Sample street'], ['City', 'Pune'], ['State', 'Maharashtra'], ['PIN code', '411001']]) await page.getByRole('textbox', { name: label, exact: true }).fill(value);
  await page.getByRole('button', { name: 'Save sample address', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove address 411001', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'App settings', exact: true }).click();
  await page.getByRole('button', { name: 'Demo connection controls', exact: true }).click();
  await page.getByRole('button', { name: 'Network: failure', exact: true }).click();
  await page.getByRole('button', { name: 'Leave demo profile', exact: true }).click();
  await expect(page.getByText('Demo network unavailable. Switch to Normal and retry.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Network: normal', exact: true }).click();
  await page.getByRole('button', { name: 'Leave demo profile', exact: true }).click();
  await page.getByRole('button', { name: 'Continue with local demo profile' }).click();
  await expect(page.getByRole('textbox', { name: 'Demo profile name', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Demo profile name', exact: true }).fill('Sample');
  await page.getByRole('button', { name: 'Open demo profile', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove address 411001', exact: true })).toBeVisible();
});
