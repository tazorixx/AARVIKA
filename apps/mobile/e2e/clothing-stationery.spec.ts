import { readyImages } from './capture';
import { test, expect } from '@playwright/test';
test('Clothing audience/spec filters, size artwork/guide and chosen SKU reach cart', async ({ page }) => {
  await page.goto('/department/clothing', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Fit, fabric & clothing filters', exact: true }).click();
  await page.getByRole('button', { name: 'Women', exact: true }).first().click();
  await page.getByRole('button', { name: 'Edit specifications', exact: true }).click();
  await page.getByRole('button', { name: 'M', exact: true }).click();
  await page.getByRole('button', { name: 'Edit specifications', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit specifications', exact: true })).toHaveAttribute('aria-expanded', 'false');
  await page.getByRole('button', { name: 'Edit specifications', exact: true }).click();
  const selectedSize = page.getByRole('button', { name: /M$/, pressed: true });
  await expect(selectedSize).toBeVisible();
  const sizeTarget = await selectedSize.boundingBox();
  expect(sizeTarget!.width).toBeGreaterThanOrEqual(44);
  expect(sizeTarget!.height).toBeGreaterThanOrEqual(44);
  await page.getByRole('button', { name: 'Blue', exact: true }).click();
  await page.getByRole('button', { name: 'View Women T-shirts · demo', exact: true }).last().click();
  await page.getByRole('button', { name: 'M · Blue', exact: true }).click();
  await expect(page.getByText('Size guide · cm', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Product details', exact: true }).click();
  await expect(page.getByText('Colour: Blue', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add to demo cart', exact: true }).click();
  await page.getByRole('button', { name: 'View cart', exact: true }).last().click();
  await expect(page.getByText('M · Blue', { exact: true }).last()).toBeVisible();
  await readyImages(page); await page.screenshot({ path: 'evidence/task-08-apparel-cart-390.png' });
});
