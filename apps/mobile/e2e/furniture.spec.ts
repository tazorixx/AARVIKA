test('Furniture source subtype uses inquiry action and local reference/photos/revisions persist', async ({ page }) => {
  const external: string[] = []; page.on('request', r => { const u = new URL(r.url()); if (u.protocol.startsWith('http') && !['localhost', '127.0.0.1'].includes(u.hostname)) external.push(u.hostname); });
  await page.goto('/category/furniture-1-1', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'View Sofas: 1–4 seater, sectional, L/corner · design concept', exact: true }).last().click();
  await expect(page.getByText('Quote required', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Request furniture quote', exact: true }).click();
  await page.getByRole('button', { name: 'Save inquiry locally', exact: true }).click();
  await expect(page.getByText('Enter positive dimensions no larger than 100 metres.', { exact: true })).toBeVisible();
  for (const [label, value] of [['Required width', '120'], ['Required depth', '60'], ['Required height', '80'], ['Requested material', 'Wood'], ['Requested finish', 'Matte'], ['Furniture budget (₹)', '15000'], ['Furniture delivery PIN', '411001'], ['Design requirements', 'Sample sofa requirements']]) await page.getByRole('textbox', { name: label, exact: true }).fill(value);
  const chooser = page.waitForEvent('filechooser'); await page.getByRole('button', { name: 'Choose reference photo', exact: true }).click();
  await (await chooser).setFiles({ name: 'reference.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a5t8AAAAASUVORK5CYII=', 'base64') });
  await expect(page.getByRole('img', { name: 'Furniture reference 1', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save inquiry locally', exact: true }).click();
  await expect(page.getByText('Custom design · Revision 1', { exact: true })).toBeVisible();
  await page.reload(); await expect(page.getByText('1 local reference photo(s)', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Revise inquiry', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Furniture reference 1', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Furniture budget (₹)', exact: true }).fill('20000');
  await page.getByRole('button', { name: 'Save inquiry locally', exact: true }).click();
  await expect(page.getByText('Custom design · Revision 2', { exact: true })).toBeVisible();
  await readyImages(page); await page.screenshot({ path: 'evidence/task-09-inquiry-revisions-390.png' });
  await page.getByRole('button', { name: 'Withdraw inquiry locally', exact: true }).click();
  await expect(page.getByText('Status: Withdrawn locally', { exact: true })).toBeVisible();
  expect(external).toEqual([]);
});
test('Furniture Commercial paths and dimension filters work at 320 pixels', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 });
  await page.goto('/department/furniture', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Furniture specifications & inquiries', exact: true }).click();
  await page.getByRole('button', { name: 'Commercial', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Clinics & Healthcare', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit furniture filters', exact: true }).click();
  await page.getByRole('textbox', { name: 'Maximum width (cm)', exact: true }).fill('130');
  await expect(page.getByRole('button', { name: 'View Billing counters and cash desks · design concept', exact: true }).last()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await readyImages(page); await page.screenshot({ path: 'evidence/task-09-commercial-320.png' });
});
