import { readyImages } from './capture';
import { test, expect } from '@playwright/test';
test('tradition filters, optional family plan and function kit lead to cart', async ({ page }) => {
  await page.goto('/department/wedding', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Wedding planning & tradition finder', exact: true }).click();
  await page.getByRole('textbox', { name: 'Find a tradition or function', exact: true }).fill('Marathi');
  await page.getByRole('button', { name: 'Explore Marathi Hindu', exact: true }).last().click();
  await page.getByRole('button', { name: 'Planning notes / Family guidance', exact: true }).click();
  await page.getByRole('switch', { name: 'Include Sakharpuda', exact: true }).click();
  await expect(page.getByRole('switch', { name: 'Include Sakharpuda', exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Explore Sakharpuda', exact: true }).last().click();
  await page.getByRole('button', { name: 'Plan this function', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Customize this function kit', exact: true })).toBeDisabled();
  await page.getByRole('switch', { name: 'I will verify kit suitability with family', exact: true }).click();
  await page.getByRole('textbox', { name: 'Return gift quantity', exact: true }).fill('3');
  await page.getByRole('button', { name: 'Customize this function kit', exact: true }).click();
  await expect(page.getByText('Preview total: ₹1,195', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '3. Finish', exact: true }).click();
  await page.getByRole('button', { name: 'Add gift box to demo cart', exact: true }).click();
  await page.getByRole('button', { name: 'View gift box in cart', exact: true }).last().click();
  await expect(page.getByText('Cotton return-gift pouch × 3', { exact: true })).toBeVisible();
  await readyImages(page); await page.screenshot({ path: 'evidence/task-05-wedding-kit-cart-390.png', fullPage: true });
  await page.goto('/department/wedding', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Wedding planning & tradition finder', exact: true }).click();
  await page.getByRole('textbox', { name: 'Your own family event', exact: true }).fill('Our welcome evening');
  await page.getByRole('button', { name: 'Add family event', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Wedding planning & tradition finder', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove custom event Our welcome evening', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Remove event Sakharpuda', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Find a tradition or function', exact: true }).fill('Anand Karaj');
  await page.getByRole('button', { name: 'Explore Punjabi Sikh', exact: true }).last().click();
  await expect(page.getByRole('button', { name: 'Explore Anand Karaj and four Laavan', exact: true })).toBeVisible();
  await readyImages(page); await page.screenshot({ path: 'evidence/task-05-sikh-functions-390.png', fullPage: true });
});
